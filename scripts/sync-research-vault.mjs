import fs from "node:fs";
import path from "node:path";
import process from "node:process";
import yaml from "js-yaml";

const vaultRoot = process.env.RESEARCH_VAULT_PATH ?? "C:\\Users\\29849\\Documents\\ResearchVault";
const outputPath = path.resolve("data/research-vault.ts");
const publicTimelinePath = path.join(vaultRoot, "public", "learning-timeline.yaml");
const registryPath = path.join(vaultRoot, "90-Systems", "learning-tree-data", "learning-tree-registry.json");

function readJson(filePath) {
  return JSON.parse(fs.readFileSync(filePath, "utf8"));
}

function readTimeline() {
  return yaml.load(fs.readFileSync(publicTimelinePath, "utf8"));
}

function cleanNode(node) {
  return {
    id: node.id,
    label: node.label,
    type: node.type,
    status: node.status,
    parent: node.parent,
    learningRole: node.learning_role,
    goal: node.learning_goal ?? node.goal,
    summary: node.learning_summary,
    readinessCriteria: node.readiness_criteria,
  };
}

function collectTree(registry) {
  return registry.track_data_files.flatMap((track) => {
    const data = readJson(path.join(vaultRoot, track.data_path.replace(/^.*ResearchVault[\\/]/u, "")));
    return (data.nodes ?? []).map(cleanNode);
  });
}

function main() {
  if (!fs.existsSync(publicTimelinePath) || !fs.existsSync(registryPath)) {
    console.warn(`[research-vault] source not found, keeping ${outputPath}`);
    return;
  }

  const timeline = readTimeline();
  const registry = readJson(registryPath);
  const payload = {
    sourceUpdatedAt: timeline.updatedAt,
    stages: timeline.stages ?? [],
    events: timeline.recentEvents ?? [],
    tree: collectTree(registry),
  };

  const source = `// Generated by scripts/sync-research-vault.mjs. Do not edit by hand.\nexport const researchVault = ${JSON.stringify(payload, null, 2)} as const;\n`;
  fs.writeFileSync(outputPath, source, "utf8");
  console.log(`[research-vault] wrote ${outputPath}`);
}

main();
